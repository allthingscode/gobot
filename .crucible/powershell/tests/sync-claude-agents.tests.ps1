# Review of 9b0bb92 (item 247): the regenerate command hardcoded .crucible, so a project with
# crucible_root: tools/crucible was told to run a script that is not there.
$results += Run-Test "Regenerate commands name the configured bundle" {
    $root = New-AgentRoot -Name "agents-tools-bundle"
    $configPath = Join-Path $root ".crucible/config.yaml"
    [System.IO.File]::WriteAllText($configPath, ("crucible_root: `"tools/crucible`"`n" + [System.IO.File]::ReadAllText($configPath)), (New-Object System.Text.UTF8Encoding $false))
    $run = Invoke-Sync -Root $root
    Assert-Result "tools bundle sync exit 0" ($run.ExitCode -eq 0) $run.Output
    $strong = Read-Agent $root "crucible-strong"
    Assert-Result "header names the configured bundle" ($strong.Contains("Regenerate with: & 'tools/crucible/powershell/sync-claude-agents.ps1' -ProjectRoot '.' -->")) $strong
    Remove-Item -LiteralPath (Join-Path $root ".claude/agents/crucible-light.md")
    Push-Location (New-TestFixtureRoot -NameHint "agents-elsewhere")
    try { $check = Invoke-Sync -Root $root -Check } finally { Pop-Location }
    $resolved = (Resolve-Path -LiteralPath $root).Path
    $advice = @($check.Output -split "`r?`n" | Where-Object { $_ -match 'regenerate with' }) -join "`n"
    Assert-Result "check advice names the bundle under the project" ($advice.Replace("\", "/").Contains(($resolved.Replace("\", "/") + "/tools/crucible/powershell/sync-claude-agents.ps1"))) $check.Output
    Assert-Result "check advice names the project root" ($advice.Contains("-ProjectRoot '" + $resolved + "'")) $check.Output
}

$results += Run-Test "Sync writes the four agent definitions with the configured full model ID and effort" {
    $root = New-AgentRoot -Name "agents-gen" -Models @"
models:
  targets:
    claude:
      strong:
        model: claude-opus-5-5
        effort: xhigh
"@
    $run = Invoke-Sync -Root $root
    Assert-Result "exit 0" ($run.ExitCode -eq 0) $run.Output
    foreach ($n in $names) {
        Assert-Result ($n + " exists") (Test-Path -LiteralPath (Join-Path $root (".claude/agents/" + $n + ".md"))) "missing"
    }
    $strong = Read-Agent $root "crucible-strong"
    Assert-Result "strong name" ($strong.Contains("`nname: crucible-strong`n")) $strong
    Assert-Result "strong model is the full ID" ($strong.Contains("`nmodel: claude-opus-5-5`n")) $strong
    Assert-Result "strong effort follows config" ($strong.Contains("`neffort: xhigh`n")) $strong
    Assert-Result "default level" ((Read-Agent $root "crucible-default").Contains("`nmodel: claude-sonnet-5-5`neffort: medium`n")) "default"
    Assert-Result "light level" ((Read-Agent $root "crucible-light").Contains("`nmodel: claude-haiku-5-5`neffort: high`n")) "light"
    Assert-Result "marker and regenerate command" ($strong.Contains("GENERATED by Crucible") -and $strong.Contains("sync-claude-agents.ps1' -ProjectRoot '.'")) $strong
    $researcher = Read-Agent $root "crucible-researcher"
    Assert-Result "researcher is strong level" ($researcher.Contains("`nmodel: claude-opus-5-5`neffort: xhigh`n")) $researcher
    Assert-Result "researcher has no editing tools" ($researcher -match '(?m)^disallowedTools: .*Write.*Edit') $researcher
    # Item 230: the brief names the outputs the Researcher must write, so it can finish without breaking a rule.
    Assert-Result "researcher may write its report and checkpoints" ($researcher.Contains(".crucible/research/") -and $researcher.Contains("task.md")) $researcher
    Assert-Result "researcher files only approved stubs" ($researcher.Contains("human-approved backlog stubs")) $researcher
    Assert-Result "no scripts-only write rule" (-not $researcher.Contains("Write nothing except through")) $researcher
    Assert-Result "tier agents do not restrict tools" ($strong -notmatch '(?m)^(disallowedTools|tools):') $strong
}

