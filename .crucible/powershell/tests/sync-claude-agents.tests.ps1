# Item 213: sync-claude-agents.ps1 writes one Claude Code agent definition per Claude level plus
# a read-only researcher, and -Check reports files that are missing or stale without writing.

$ErrorActionPreference = "Stop"
Set-StrictMode -Version Latest

$REPO_ROOT = (Resolve-Path -Path "$PSScriptRoot/../..").Path
. (Join-Path $PSScriptRoot '_harness.ps1')
. (Join-Path $REPO_ROOT "powershell/crucible-lib.ps1")
. (Join-Path $REPO_ROOT "powershell/lib/claude-agents.ps1")

$SYNC = Join-Path $REPO_ROOT "powershell/sync-claude-agents.ps1"
$results = @()

function New-AgentRoot {
    param([string]$Name, [string]$Models = "models:`n")
    $root = New-TestFixtureRoot -NameHint $Name
    New-Item -ItemType Directory -Path (Join-Path $root ".crucible") -Force | Out-Null
    $body = "project:`n  name: Tmp`n" + $Models.TrimEnd() + "`nverification:`n  quick: []`n"
    [System.IO.File]::WriteAllText((Join-Path $root ".crucible/config.yaml"), $body, (New-Object System.Text.UTF8Encoding $false))
    return $root
}

function Invoke-Sync {
    param([string]$Root, [switch]$Check)
    $args = @("-NoProfile", "-File", $SYNC, "-ProjectRoot", $Root)
    if ($Check) { $args += "-Check" }
    $output = & (Get-PwshCommand) @args 2>&1 | Out-String
    return [pscustomobject]@{ ExitCode = $LASTEXITCODE; Output = $output }
}

function Read-Agent {
    param([string]$Root, [string]$Name)
    return [System.IO.File]::ReadAllText((Join-Path $Root (".claude/agents/" + $Name + ".md")), (New-Object System.Text.UTF8Encoding $false))
}

$names = @("crucible-strong", "crucible-default", "crucible-light", "crucible-researcher")

