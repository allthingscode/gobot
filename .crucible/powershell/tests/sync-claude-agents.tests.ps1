    }
}

$results += Run-Test "Generated agent files are ASCII, BOM-free, LF, and byte-identical when regenerated" {
    $root = New-AgentRoot -Name "agents-bytes"
    Invoke-Sync -Root $root | Out-Null
    $before = @{}
    foreach ($n in $names) {
        $path = Join-Path $root (".claude/agents/" + $n + ".md")
        $bytes = [System.IO.File]::ReadAllBytes($path)
        $before[$n] = $bytes
        Assert-Result ($n + " no BOM") (-not ($bytes.Length -ge 3 -and $bytes[0] -eq 0xEF -and $bytes[1] -eq 0xBB)) "BOM"
        Assert-Result ($n + " ASCII") (-not ($bytes | Where-Object { $_ -gt 127 })) "non-ASCII byte"
        Assert-Result ($n + " LF only") (-not ($bytes -contains 13)) "CR byte"
        Assert-Result ($n + " starts with frontmatter") ([System.Text.Encoding]::ASCII.GetString($bytes, 0, 4) -eq "---`n") "no frontmatter"
    }
    Invoke-Sync -Root $root | Out-Null
    foreach ($n in $names) {
        $after = [System.IO.File]::ReadAllBytes((Join-Path $root (".claude/agents/" + $n + ".md")))
        Assert-Result ($n + " identical") ([Convert]::ToBase64String($after) -eq [Convert]::ToBase64String($before[$n])) "bytes changed on regenerate"
    }
}

$results += Run-Test "-Check: missing, stale and clean; it never writes" {
    $root = New-AgentRoot -Name "agents-check"
    $missing = Invoke-Sync -Root $root -Check
    Assert-Result "missing exits non-zero" ($missing.ExitCode -ne 0) $missing.Output
    Assert-Result "missing lists the files" ($missing.Output -match 'missing: crucible-strong' -and $missing.Output -match 'missing: crucible-researcher') $missing.Output
    Assert-Result "check wrote nothing" (-not (Test-Path -LiteralPath (Join-Path $root ".claude"))) "wrote files"

    Invoke-Sync -Root $root | Out-Null
    $clean = Invoke-Sync -Root $root -Check
    Assert-Result "clean exits 0" ($clean.ExitCode -eq 0) $clean.Output

    $path = Join-Path $root ".claude/agents/crucible-default.md"
    [System.IO.File]::WriteAllText($path, ((Read-Agent $root "crucible-default") -replace 'effort: medium', 'effort: low'), (New-Object System.Text.UTF8Encoding $false))
    $stale = Invoke-Sync -Root $root -Check
    Assert-Result "stale exits non-zero" ($stale.ExitCode -ne 0) $stale.Output
    Assert-Result "stale names only the drifted file" ($stale.Output -match 'stale: crucible-default' -and $stale.Output -notmatch 'crucible-strong') $stale.Output
    Assert-Result "check left the stale file alone" ((Read-Agent $root "crucible-default").Contains("effort: low")) "check rewrote the file"

    $crlf = (Read-Agent $root "crucible-light") -replace "`n", "`r`n"
    [System.IO.File]::WriteAllText((Join-Path $root ".claude/agents/crucible-light.md"), $crlf, (New-Object System.Text.UTF8Encoding $false))
    Assert-Result "a CRLF checkout is not drift" ((Invoke-Sync -Root $root -Check).Output -notmatch 'crucible-light') "CRLF flagged"
}

$results += Run-Test "A config change makes the existing files stale, and a sync repairs them" {
    $root = New-AgentRoot -Name "agents-config-change"
    Invoke-Sync -Root $root | Out-Null
    $cfg = Join-Path $root ".crucible/config.yaml"
    [System.IO.File]::WriteAllText($cfg, "project:`n  name: Tmp`nmodels:`n  targets:`n    claude:`n      light:`n        model: claude-haiku-5-5`n        effort: low`nverification:`n  quick: []`n", (New-Object System.Text.UTF8Encoding $false))
    $drift = Invoke-Sync -Root $root -Check
    Assert-Result "light is stale" ($drift.ExitCode -ne 0 -and $drift.Output -match 'stale: crucible-light') $drift.Output
    Invoke-Sync -Root $root | Out-Null
    Assert-Result "light now at low" ((Read-Agent $root "crucible-light").Contains("`neffort: low`n")) "not regenerated"
    Assert-Result "clean again" ((Invoke-Sync -Root $root -Check).ExitCode -eq 0) "still drifting"
}

$results += Run-Test "Sync touches only crucible-*.md in .claude/agents" {
    $root = New-AgentRoot -Name "agents-others"
    $dir = Join-Path $root ".claude/agents"
    New-Item -ItemType Directory -Path $dir -Force | Out-Null
    $mine = Join-Path $dir "reviewer.md"
    $other = Join-Path $dir "crucible.md"
    [System.IO.File]::WriteAllText($mine, "---`nname: reviewer`n---`nhand-written`n", (New-Object System.Text.UTF8Encoding $false))
    [System.IO.File]::WriteAllText($other, "hand-written`n", (New-Object System.Text.UTF8Encoding $false))
    Invoke-Sync -Root $root | Out-Null
    Assert-Result "other agent untouched" ([System.IO.File]::ReadAllText($mine).Contains("hand-written")) "reviewer.md rewritten"
    Assert-Result "non-prefixed file untouched" ([System.IO.File]::ReadAllText($other) -eq "hand-written`n") "crucible.md rewritten"
    $written = @(Get-ChildItem -LiteralPath $dir -File | ForEach-Object Name | Sort-Object)
    Assert-Result "only the four generated files were added" (($written -join ",") -eq "crucible-default.md,crucible-light.md,crucible-researcher.md,crucible-strong.md,crucible.md,reviewer.md") ($written -join ",")
}

$results += Run-Test "Item 214: ignored agents warn with an actionable directory exception" {
    $root = New-AgentRoot -Name "agents-ignored"
    git -C $root init --quiet
    [IO.File]::WriteAllText((Join-Path $root ".gitignore"), ".claude/`n")
    $run = Invoke-Sync -Root $root
    Assert-Result "ignored warning" ($run.Output -match 'git-ignored') $run.Output
    Assert-Result "fix names both rules" ($run.Output.Contains('.claude/*') -and $run.Output.Contains('!.claude/agents/')) $run.Output
    [IO.File]::WriteAllText((Join-Path $root ".gitignore"), ".claude/*`n!.claude/agents/`n")
    Assert-Result "exception removes warning" ((Invoke-Sync -Root $root).Output -notmatch 'git-ignored') "still ignored"
}

